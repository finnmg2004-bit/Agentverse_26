#!/usr/bin/env python3
"""
Convert the police light bar GLB into MuJoCo meshes — run with `pixi run prepare-lightbar`.

Source: assets/lightbar/police_lights.glb — "Police Lights" by KIDosn,
https://sketchfab.com/3d-models/police-lights-54321f506475441c8f92abdaa740b2d6, CC BY 4.0.

The GLB has one textured lamp mesh whose lenses are clear grey in the base-colour map; the
red/blue colour only lives in the emissive map, and the centre is a dark checker panel. We split
the lamp's triangles by texture region into four OBJ meshes so the sim can light each lens
separately (own material -> runtime colour + emission):
  lightbar_housing.obj   body, end caps, feet          (textured with lightbar.png)
  lightbar_red.obj       left lens  (emissive red)
  lightbar_center.obj    centre panel (checker)        -> becomes a clear lens in the sim
  lightbar_blue.obj      right lens (emissive blue)
Frame: metres, Z up, long axis along +Y (across the robot), bottom at z = 0, centred on x = y = 0,
red lens on +Y (robot's left). Length = LENGTH_M. Pure numpy/OpenCV GLB reader, no extra deps.
"""

from __future__ import annotations

import json
import struct
import sys
from pathlib import Path

import cv2
import numpy as np

PROJECT_ROOT = Path(__file__).resolve().parent.parent
LB_DIR = PROJECT_ROOT / "assets" / "lightbar"
SRC = LB_DIR / "police_lights.glb"
LENGTH_M = 0.20  # bar length across the Go2's back
LAMP_NODE = "Police Lamp_3"  # the four "Reflection *" nodes are tiny inner reflectors; skipped

COMP = {5120: np.int8, 5121: np.uint8, 5122: np.int16, 5123: np.uint16, 5125: np.uint32, 5126: np.float32}
NCOMP = {"SCALAR": 1, "VEC2": 2, "VEC3": 3, "VEC4": 4, "MAT4": 16}


def load_glb(path: Path):
    b = path.read_bytes()
    jlen = struct.unpack("<I", b[12:16])[0]
    j = json.loads(b[20:20 + jlen])
    binchunk = b[20 + jlen + 8:]

    def accessor(i: int) -> np.ndarray:
        a = j["accessors"][i]
        bv = j["bufferViews"][a["bufferView"]]
        dt, n = np.dtype(COMP[a["componentType"]]), NCOMP[a["type"]]
        start = bv.get("byteOffset", 0) + a.get("byteOffset", 0)
        stride = bv.get("byteStride", dt.itemsize * n)
        raw = np.frombuffer(binchunk, np.uint8, count=stride * (a["count"] - 1) + dt.itemsize * n, offset=start)
        rows = np.lib.stride_tricks.as_strided(raw, (a["count"], dt.itemsize * n), (stride, 1))
        return np.ascontiguousarray(rows).view(dt).reshape(a["count"], n)

    def image(i: int) -> np.ndarray:
        bv = j["bufferViews"][j["images"][j["textures"][i]["source"]]["bufferView"]]
        data = binchunk[bv.get("byteOffset", 0): bv.get("byteOffset", 0) + bv["byteLength"]]
        return cv2.imdecode(np.frombuffer(data, np.uint8), cv2.IMREAD_COLOR)

    return j, accessor, image


def node_matrix(n: dict) -> np.ndarray:
    if "matrix" in n:
        return np.array(n["matrix"], dtype=float).reshape(4, 4).T  # glTF is column-major
    t = np.array(n.get("translation", [0, 0, 0]), float)
    x, y, z, w = n.get("rotation", [0, 0, 0, 1])
    r = np.array([[1 - 2 * (y * y + z * z), 2 * (x * y - z * w), 2 * (x * z + y * w)],
                  [2 * (x * y + z * w), 1 - 2 * (x * x + z * z), 2 * (y * z - x * w)],
                  [2 * (x * z - y * w), 2 * (y * z + x * w), 1 - 2 * (x * x + y * y)]])
    m = np.eye(4)
    m[:3, :3] = r * np.array(n.get("scale", [1, 1, 1]), float)
    m[:3, 3] = t
    return m


def world_meshes(j: dict):
    """Yield (node_name, mesh_index, world_matrix) for every mesh node in the default scene."""
    def walk(i: int, parent: np.ndarray, owner: str):
        n = j["nodes"][i]
        m = parent @ node_matrix(n)
        name = n.get("name", owner)
        if "mesh" in n:
            yield owner, n["mesh"], m
        for c in n.get("children", []):
            yield from walk(c, m, name if "mesh" not in n else owner)
    for root in j["scenes"][j.get("scene", 0)]["nodes"]:
        yield from walk(root, np.eye(4), "")


def write_obj(path: Path, v: np.ndarray, vt: np.ndarray, vn: np.ndarray, tris: np.ndarray) -> None:
    used = np.unique(tris)
    remap = -np.ones(len(v), int)
    remap[used] = np.arange(len(used)) + 1
    lines = [f"# Generated by scripts/prepare_lightbar.py from police_lights.glb (KIDosn, CC BY 4.0)"]
    lines += ["v {:.6f} {:.6f} {:.6f}".format(*p) for p in v[used]]
    lines += ["vt {:.6f} {:.6f}".format(*t) for t in vt[used]]
    lines += ["vn {:.5f} {:.5f} {:.5f}".format(*q) for q in vn[used]]
    lines += ["f " + " ".join(f"{k}/{k}/{k}" for k in remap[t]) for t in tris]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    if not SRC.exists():
        sys.exit(f"[lightbar] missing {SRC} — download 'Police Lights' (KIDosn) as GLB 1k from Sketchfab")
    j, accessor, image = load_glb(SRC)
    lamp = [(mi, m) for name, mi, m in world_meshes(j) if name == LAMP_NODE]
    if not lamp:
        sys.exit(f"[lightbar] node {LAMP_NODE!r} not found")
    mesh_i, mw = lamp[0]
    prim = j["meshes"][mesh_i]["primitives"][0]
    pos = accessor(prim["attributes"]["POSITION"]).astype(float)
    nrm = accessor(prim["attributes"]["NORMAL"]).astype(float)
    uv = accessor(prim["attributes"]["TEXCOORD_0"]).astype(float)
    tris = accessor(prim["indices"]).reshape(-1, 3).astype(int)

    # glTF (Y up) world coords -> body frame: X = glTF z (depth), Y = glTF x (long axis), Z = glTF y (up)
    pw = (mw @ np.c_[pos, np.ones(len(pos))].T).T[:, :3]
    nw = (np.linalg.inv(mw[:3, :3]).T @ nrm.T).T
    nw /= np.linalg.norm(nw, axis=1, keepdims=True) + 1e-12
    v = pw[:, [2, 0, 1]]
    vn = nw[:, [2, 0, 1]]

    # Classify triangles by the texture under their UV centroid.
    mat = j["materials"][prim["material"]]
    emis = image(mat["emissiveTexture"]["index"]).astype(int)  # BGR
    base = image(mat["pbrMetallicRoughness"]["baseColorTexture"]["index"])
    h, w = emis.shape[:2]
    c_uv = uv[tris].mean(axis=1)
    px = np.clip((c_uv[:, 0] * w).astype(int), 0, w - 1)
    py = np.clip((c_uv[:, 1] * h).astype(int), 0, h - 1)  # glTF v runs top -> bottom, like image rows
    e = emis[py, px]
    bc = base[py, px].astype(int)  # BGR; the end caps are painted solid red / blue in the base map
    is_red = ((e[:, 2] > 128) & (e[:, 0] < 100)) | ((bc[:, 2] > 170) & (bc[:, 1] < 80) & (bc[:, 0] < 80))
    is_blue = ((e[:, 0] > 128) & (e[:, 2] < 100)) | ((bc[:, 0] > 110) & (bc[:, 2] < 80) & (bc[:, 1] < 80))
    is_center = (~is_red) & (~is_blue) & (c_uv[:, 0] > 0.625)  # dark checker panel region of the base map
    parts = {"red": is_red, "blue": is_blue, "center": is_center}

    # Normalise: scale long axis to LENGTH_M, bottom at z = 0, centre x/y; red lens on +Y.
    s = LENGTH_M / np.ptp(v[:, 1])
    v = v * s
    v -= [(v[:, 0].min() + v[:, 0].max()) / 2, (v[:, 1].min() + v[:, 1].max()) / 2, v[:, 2].min()]
    if v[np.unique(tris[is_red])][:, 1].mean() < 0:  # mirror-free 180 deg yaw so red sits on +Y
        v[:, :2] *= -1
        vn[:, :2] *= -1

    vt = np.c_[uv[:, 0], 1.0 - uv[:, 1]]  # OBJ/MuJoCo v runs bottom -> top
    LB_DIR.mkdir(parents=True, exist_ok=True)
    housing = ~(is_red | is_blue | is_center)
    write_obj(LB_DIR / "lightbar_housing.obj", v, vt, vn, tris[housing])
    for name, mask in parts.items():
        write_obj(LB_DIR / f"lightbar_{name}.obj", v, vt, vn, tris[mask])
    cv2.imwrite(str(LB_DIR / "lightbar.png"), base)

    print(f"[lightbar] {len(tris)} tris: housing {housing.sum()}, red {is_red.sum()}, "
          f"center {is_center.sum()}, blue {is_blue.sum()}")
    print(f"[lightbar] size {np.ptp(v[:, 0]):.3f} x {np.ptp(v[:, 1]):.3f} x {np.ptp(v[:, 2]):.3f} m "
          f"(depth x length x height)")
    for name, mask in parts.items():
        pv = v[np.unique(tris[mask])]
        print(f"[lightbar] {name:6s} lens y {pv[:, 1].min():+.3f}..{pv[:, 1].max():+.3f}  "
              f"z {pv[:, 2].min():.3f}..{pv[:, 2].max():.3f}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
